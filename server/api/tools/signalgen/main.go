// Command signalgen 读取 api/signal 下的信令契约（JSON Schema），
// 生成两侧 package signal 的 protocol_gen.go（server 与 client 字节相同）。
//
// 用法（在仓库任意位置）：
//
//	go run ./server/api/tools/signalgen          # 从 CWD 向上找 api/signal
//	go run ./server/api/tools/signalgen -root .. # 显式指定仓库根
//
// 幂等：重复运行输出不变。生成物禁止手改，改契约请改 api/signal/。
package main

import (
	"flag"
	"fmt"
	"os"
	"path/filepath"
)

func main() {
	root := flag.String("root", "", "仓库根目录（含 api/signal）；缺省从 CWD 向上查找")
	flag.Parse()
	base, err := findRoot(*root)
	if err != nil {
		fmt.Fprintln(os.Stderr, "signalgen:", err)
		os.Exit(1)
	}
	if err := run(base); err != nil {
		fmt.Fprintln(os.Stderr, "signalgen:", err)
		os.Exit(1)
	}
}

// run 生成并写两侧 protocol_gen.go。
func run(root string) error {
	cat, err := loadCatalog(filepath.Join(root, "api", "signal", "catalog.json"))
	if err != nil {
		return err
	}
	comps, err := loadComponents(filepath.Join(root, "api", "signal", "components.schema.json"))
	if err != nil {
		return err
	}
	msgs, err := loadMessages(filepath.Join(root, "api", "signal", "messages"))
	if err != nil {
		return err
	}
	body, err := emit(cat, comps, msgs)
	if err != nil {
		return err
	}
	for _, rel := range []string{
		filepath.Join("server", "internal", "signal", "protocol_gen.go"),
		filepath.Join("client", "internal", "signal", "protocol_gen.go"),
	} {
		if err := os.WriteFile(filepath.Join(root, rel), body, 0o644); err != nil {
			return fmt.Errorf("写 %s: %w", rel, err)
		}
	}
	return nil
}

// findRoot 定位仓库根：显式 -root 优先，否则自 CWD 向上找 api/signal/catalog.json。
func findRoot(explicit string) (string, error) {
	start := explicit
	if start == "" {
		wd, err := os.Getwd()
		if err != nil {
			return "", err
		}
		start = wd
	}
	dir, err := filepath.Abs(start)
	if err != nil {
		return "", err
	}
	for {
		if _, err := os.Stat(filepath.Join(dir, "api", "signal", "catalog.json")); err == nil {
			return dir, nil
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			if explicit != "" {
				return "", fmt.Errorf("%s 下没有 api/signal/catalog.json", explicit)
			}
			return "", fmt.Errorf("从 %s 向上找不到 api/signal/catalog.json（用 -root 指定仓库根）", start)
		}
		dir = parent
	}
}

