package main

import (
	"context"
	"fmt"
	"go/format"
	"os"
	"sort"
	"strings"

	"github.com/getkin/kin-openapi/openapi3"
	"github.com/oapi-codegen/oapi-codegen/v2/pkg/codegen"
	"github.com/oapi-codegen/oapi-codegen/v2/pkg/util"
)

// genGo 读 spec → 校验 → 生成 server/internal/api/api.gen.go。
// 模式固定 types + std-http-server + strict-server：
// 实现层只实现生成的 StrictServerInterface，请求/响应类型与 spec 同源。
func genGo(specPath, outPath string) error {
	swagger, err := util.LoadSwagger(specPath)
	if err != nil {
		return fmt.Errorf("加载 %s: %w", specPath, err)
	}
	if err := swagger.Validate(context.Background()); err != nil {
		return fmt.Errorf("校验 %s: %w", specPath, err)
	}
	opts := codegen.Configuration{
		PackageName: "api",
		Generate: codegen.GenerateOptions{
			Models:        true,
			StdHTTPServer: true,
			Strict:        true,
		},
	}
	if err := opts.Validate(); err != nil {
		return fmt.Errorf("生成配置: %w", err)
	}
	src, err := codegen.Generate(swagger, opts)
	if err != nil {
		return fmt.Errorf("生成 Go: %w", err)
	}
	src = ensureBanner(src) + publicPatternsSource(swagger)
	// 整文件再过一遍 gofmt：banner/路由表拼接后缩进可能不齐，CI 的 gofmt 门会拦。
	formatted, err := format.Source([]byte(src))
	if err != nil {
		return fmt.Errorf("gofmt 生成物: %w", err)
	}
	if err := os.WriteFile(outPath, formatted, 0o644); err != nil {
		return fmt.Errorf("写 %s: %w", outPath, err)
	}
	return nil
}

// ensureBanner 保证生成物首行有 DO NOT EDIT 头（CI 检查靠它识别生成文件）。
func ensureBanner(src string) string {
	const banner = "// Code generated by openapigen (oapi-codegen) from api/openapi.yaml. DO NOT EDIT.\n"
	if strings.Contains(src, "DO NOT EDIT.") {
		return src
	}
	return banner + src
}

// publicPatternsSource 从 spec 的 security:[] 操作生成免鉴权路由表。
// authMux 依此决定是否套 Bearer 鉴权；未列出的路由默认要求登录（fail-closed）。
// 模式串与 stdhttp 路由注册格式一致（"METHOD /path"，BaseURL 为空）。
func publicPatternsSource(swagger *openapi3.T) string {
	var pats []string
	for path, item := range swagger.Paths.Map() {
		if item == nil {
			continue
		}
		for method, op := range item.Operations() {
			// Security 显式为 [] = 免鉴权；nil = 继承根 security（需鉴权）。
			if op.Security != nil && len(*op.Security) == 0 {
				pats = append(pats, strings.ToUpper(method)+" "+path)
			}
		}
	}
	sort.Strings(pats)
	var b strings.Builder
	b.WriteString("\n// PublicRoutePatterns 免鉴权路由（openapi.yaml 中 security: [] 的操作）。\n")
	b.WriteString("// 由 openapigen 生成；未列出的路由一律要求 Bearer 鉴权。\n")
	b.WriteString("var PublicRoutePatterns = map[string]bool{\n")
	for _, p := range pats {
		fmt.Fprintf(&b, "\t%q: true,\n", p)
	}
	b.WriteString("}\n")
	return b.String()
}
